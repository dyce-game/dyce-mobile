"""Builds the app's starter looks from assets/avatar-profiles (docs/AVATAR_GUIDEBOOK.md section 7, Phase A).

Run from the repo root:  python tools/avatar/make_starter_looks.py
Writes:
  assets/avatar-profiles/thumb/dyce_av_NNN.webp   256px thumbnails (the app bundles these, about 2 MB in all)
  src/features/avatar/starter-looks.ts            id, skin tone, hair type and a spoken description for each look
  src/features/avatar/starter-images.ts           the static require() table Metro needs

Needs Pillow. The 1024px originals stay in assets/ for marketing and the future render service.
"""
import json
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'assets', 'avatar-profiles')
OUT = os.path.join(ROOT, 'src', 'features', 'avatar')

HAIR = {
    'afro/coily': 'afro',
    'braids/locs/twists': 'braids',
    'straight/wavy/short': 'straight',
    'bald': 'bald',
    'covered': 'covered',
}

profiles = json.load(open(os.path.join(SRC, 'profiles.json'), encoding='utf8'))
os.makedirs(os.path.join(SRC, 'thumb'), exist_ok=True)

looks = []
for p in sorted(profiles, key=lambda x: x['id']):
    n = int(p['id'].split('_')[-1])
    im = Image.open(os.path.join(SRC, p['file'])).convert('RGB').resize((256, 256), Image.LANCZOS)
    im.save(os.path.join(SRC, 'thumb', os.path.basename(p['file'])), 'WEBP', quality=80, method=6)
    parts = [p['skin'], p['hair']] + ([p['headwear']] if p['headwear'] else []) + ([p['facial_hair']] if p['facial_hair'] else [])
    looks.append({
        'id': p['id'],
        'n': n,
        'skin': p['skin_group'],
        'hair': HAIR[p['hair_type']],
        'label': ', '.join(parts),
    })

header = '// Generated by tools/avatar/make_starter_looks.py from assets/avatar-profiles. Do not edit by hand.\n'
with open(os.path.join(OUT, 'starter-looks.ts'), 'w', encoding='utf8') as f:
    f.write(header)
    f.write("export type SkinTone = 'light' | 'tan' | 'brown' | 'deep';\n")
    f.write("export type HairType = 'afro' | 'braids' | 'straight' | 'bald' | 'covered';\n\n")
    f.write('export type StarterLook = {\n  id: string;\n  skin: SkinTone;\n  hair: HairType;\n  /** Spoken description for screen readers, e.g. "caramel brown, fulani braids with beads". */\n  label: string;\n};\n\n')
    f.write('export const STARTER_LOOKS: StarterLook[] = [\n')
    for l in looks:
        f.write('  { id: %s, skin: %s, hair: %s, label: %s },\n' % (json.dumps(l['id']), json.dumps(l['skin']), json.dumps(l['hair']), json.dumps(l['label'])))
    f.write('];\n')

with open(os.path.join(OUT, 'starter-images.ts'), 'w', encoding='utf8') as f:
    f.write(header)
    f.write("/* eslint-disable @typescript-eslint/no-require-imports -- Metro resolves static images through require() */\n")
    f.write("import type { ImageSourcePropType } from 'react-native';\n\n")
    f.write('export const STARTER_IMAGES: Record<string, ImageSourcePropType> = {\n')
    for l in looks:
        f.write("  %s: require('../../../assets/avatar-profiles/thumb/%s.webp'),\n" % (l['id'], l['id']))
    f.write('};\n')
print(len(looks), 'looks')
